function t(string $text): string
{
    $translations = app_translations();
    return $translations[$text] ?? $text;
}

function t_format(string $text, array $values): string
{
    $translated = t($text);
    foreach ($values as $name => $value) {
        $translated = str_replace('{' . $name . '}', (string)$value, $translated);
    }
    return $translated;
}

function t_notification(string $message): string
{
    if (preg_match('/^New borrow request submitted for (\d+) item\\(s\\) \\(Request #(\\d+)\\)$/', $message, $matches)) {
        return t_format('New borrow request submitted for {quantity} item(s) (Request #{id})', [
            'quantity' => $matches[1],
            'id' => $matches[2],
        ]);
    }

    if (preg_match('/^Your request for (\\d+) (.+) item\\(s\\) was approved\\.$/', $message, $matches)) {
        return t_format('Your request for {quantity} {equipment} item(s) was approved.', [
            'quantity' => $matches[1],
            'equipment' => $matches[2],
        ]);
    }

    if (preg_match('/^Your request for (.+) was rejected\\.$/', $message, $matches)) {
        return t_format('Your request for {equipment} was rejected.', ['equipment' => $matches[1]]);
    }

    if (preg_match('/^Your borrowed item (.+) was marked as (.+)\\.$/', $message, $matches)) {
        return t_format('Your borrowed item {equipment} was marked as {status}.', [
            'equipment' => $matches[1],
            'status' => t(ucfirst($matches[2])),
        ]);
    }

    return $message;
}
