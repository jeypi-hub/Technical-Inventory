<?php

function app_language(): string
{
    $language = $_SESSION['user']['language'] ?? 'en';
    return in_array($language, ['en', 'tl', 'ceb'], true) ? $language : 'en';
}

function app_language_tag(): string
{
    return app_language();
}

function app_theme(): string
{
    return !empty($_SESSION['user']['dark_mode']) ? 'dark' : 'light';
}

function app_compact_mode(): bool
{
    return !empty($_SESSION['user']['compact_mode']);
}

